// Writes data/providers.json from the models.dev catalog.
//
// Run it by hand when you want to refresh the list:
//
//     node scripts/snapshot-providers.mjs
//
// Why a snapshot rather than a fetch at run time: the full catalog is ~5 MB of
// 221 providers, the app has no server to cache it on, and a picker that needs
// the network to render is a picker that is sometimes empty. This writes the
// slice we actually offer — a few hundred KB — into data/, which is where this
// app already keeps the things it is handed at start-up.
//
// `node:` imports are fine here. This is a script, not app code; the rule in
// AGENTS.md is about lib/ and components/, which run in the browser.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE = "https://models.dev/api.json";
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "data", "providers.json");

/**
 * The providers we offer, and how each one is spoken to.
 *
 * `sdk` picks the AI SDK package in lib/providers.ts. Native wherever a
 * first-party package exists, because a compatibility endpoint is not the same
 * API: Anthropic's documents `response_format` as **ignored**, which would
 * silently cost the model its schema and quietly rig the comparison.
 *
 * Everything with a first-party package also has `api: null` in the catalog —
 * the package already knows its own URL. That is the whole reason the Settings
 * form can ask for a key and nothing else.
 */
const OFFERED = {
  openai: { sdk: "openai" },
  anthropic: { sdk: "anthropic" },
  google: { sdk: "google" },
  // One entry, and the reason the list can stop here: OpenRouter fronts most
  // of the rest — Groq, DeepSeek, Mistral, xAI and a few hundred more — behind
  // one key and one OpenAI-shaped endpoint. A separate entry per provider
  // would be another npm package each to reach models this already reaches.
  openrouter: { sdk: "openai-compatible" },
};

/** Keep the snapshot to models that can actually do the job. See below. */
const NEEDS_STRUCTURED_OUTPUT = true;

const catalog = await fetch(SOURCE).then((response) => {
  if (!response.ok) throw new Error(`${SOURCE} returned ${response.status}`);
  return response.json();
});

const providers = [];
for (const [id, extra] of Object.entries(OFFERED)) {
  const entry = catalog[id];
  if (!entry) {
    console.warn(`! ${id} is not in the catalog any more — skipped`);
    continue;
  }

  /*
    Only models that report structured output.

    This is a fairness filter, not a tidiness one. Plenty of models cannot do
    it — of Mistral's 34, three; of Groq's 16, five. A free-text model field lets
    someone pick one that structurally cannot answer the question, watch the LLM
    column lose, and read that as a fact about LLMs. It is a fact about the
    pick. Models that cannot play are not offered.
  */
  const models = Object.values(entry.models ?? {})
    .filter((model) => !NEEDS_STRUCTURED_OUTPUT || model.structured_output)
    .map((model) => ({
      id: model.id,
      name: model.name ?? model.id,
      // Per million tokens, for the read-out. Absent on local models.
      cost: model.cost ? { input: model.cost.input, output: model.cost.output } : null,
    }))
    .sort((one, two) => one.name.localeCompare(two.name));

  if (models.length === 0) {
    console.warn(`! ${id} has no structured-output models — skipped`);
    continue;
  }

  providers.push({
    id,
    name: entry.name ?? id,
    sdk: extra.sdk,
    // Null for every first-party package: the SDK holds its own default. Only
    // the openai-compatible ones need one, and then it is the catalog's.
    api: entry.api ?? null,
    local: extra.local ?? false,
    doc: entry.doc ?? null,
    models,
  });
}

/**
 * The escape hatch, and not from the catalog: it is the case where the user
 * has something the catalog has never heard of. Ollama, vLLM, an internal
 * gateway. No model list, because nobody knows what is loaded on it.
 */
providers.push({
  id: "custom",
  name: "Other (OpenAI-compatible)",
  sdk: "openai-compatible",
  api: null,
  local: false,
  doc: null,
  models: [],
});

const snapshot = {
  source: SOURCE,
  takenAt: new Date().toISOString().slice(0, 10),
  note: "Generated by scripts/snapshot-providers.mjs. Do not edit by hand.",
  providers,
};

writeFileSync(OUT, `${JSON.stringify(snapshot, null, 2)}\n`);

const total = providers.reduce((sum, one) => sum + one.models.length, 0);
console.log(`wrote ${OUT}`);
console.log(`${providers.length} providers, ${total} models`);
for (const one of providers) {
  console.log(`  ${one.id.padEnd(12)} ${String(one.models.length).padStart(4)} models  sdk=${one.sdk}`);
}
